import java.util;
class largest {
    public static void main(string [] args){
        Scanner sc = new scanner(system.in);
        int a = sc.nextinr();
        int b = sc.nextinr();
        int c = sc.nextinr();
        int largest = Math.max(a,Math,max(b,c));
        System.out.println("largest = "+ largest);
    }
}